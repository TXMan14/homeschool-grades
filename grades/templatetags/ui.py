@register.simple_tag
def icon(name, size=18):
    return format_html(
        '<svg class="icon" width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>',
        size, size, mark_safe(ICONS.get(name, "")),
    )


@register.filter
def grade_class(letter):
    letter = (letter or "").strip().upper()
    if not letter:
        return "none"
    first = letter[0]
    return first.lower() if first in "ABCDFP" else "none"


@register.filter
def initials(student):
    return (student.first_name[:1] + student.last_name[:1]).upper()


@register.filter
def avatar_color(obj):
    return f"av-{(obj.pk or 0) % 6}"


@register.simple_tag(takes_context=True)
def nav_active(context, prefix):
    path = context["request"].path
    if prefix == "/":
        return "active" if path == "/" else ""
    return "active" if path.startswith(prefix) else ""


@register.filter
def pct_width(value):
    try:
        return max(0, min(100, round(float(value))))
    except (TypeError, ValueError):
        return 0
